// Generates the two build-time artifacts the event tracker needs:
//
//   public/service-worker.js   <- scripts/service-worker.template.js with the
//                                 __SW_VERSION__ / __LAMBDA_URL__ / __TENANT_NAME__
//                                 / __BUILD_TIME__ placeholders filled in
//   src/generated/buildInfo.js <- the same values as an ES module, imported by
//                                 sendEventNow.js (the immediate send path)
//
// Runs automatically before `npm run dev` and `npm run build` (see package.json
// pre-scripts). Inputs come from the environment; a local .env is read as a
// convenience so `npm run dev` works without exporting anything.
//
//   SW_VERSION        build id. CI passes gh-<run>-<sha>. Falls back to
//                     GITHUB_RUN_NUMBER, then a dev timestamp.
//   VITE_LAMBDA_URL   events endpoint, no trailing slash (LAMBDA_URL also accepted)
//   VITE_TENANT_NAME  tenant header value (TENANT_NAME also accepted)
//   VITE_BASE         app base path ("/" locally, "/<repo>/" on Pages) — the SW
//                     uses it for the PWA precache list and navigation fallback

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// --- tiny .env loader (no dependency); never overrides a real env var --------
function loadDotEnv(file) {
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith("#")) continue;
    const key = m[1];
    const val = m[2].replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = val;
  }
}
loadDotEnv(resolve(root, ".env"));
loadDotEnv(resolve(root, ".env.local"));

// --- resolve inputs --------------------------------------------------------
function buildId() {
  if (process.env.SW_VERSION) return process.env.SW_VERSION;
  if (process.env.GITHUB_RUN_NUMBER) return `gh-${process.env.GITHUB_RUN_NUMBER}`;
  return `dev-${new Date().toISOString().replace(/[:.]/g, "-")}`;
}

const SW_VERSION = buildId();
const LAMBDA_URL = (process.env.VITE_LAMBDA_URL || process.env.LAMBDA_URL || "").replace(/\/+$/, "");
const TENANT_NAME = process.env.VITE_TENANT_NAME || process.env.TENANT_NAME || "storefront.local";
// Match Vite: base must start and end with "/".
let BASE_URL = process.env.VITE_BASE || "/";
if (!BASE_URL.startsWith("/")) BASE_URL = "/" + BASE_URL;
if (!BASE_URL.endsWith("/")) BASE_URL += "/";
const BUILD_TIME = new Date().toISOString();

// --- 1) service worker ---------------------------------------------------------
const template = readFileSync(resolve(root, "scripts/service-worker.template.js"), "utf8");
const sw = template
  .replaceAll("__SW_VERSION__", SW_VERSION)
  .replaceAll("__LAMBDA_URL__", LAMBDA_URL)
  .replaceAll("__TENANT_NAME__", TENANT_NAME)
  .replaceAll("__BASE_URL__", BASE_URL)
  .replaceAll("__BUILD_TIME__", BUILD_TIME);
mkdirSync(resolve(root, "public"), { recursive: true });
writeFileSync(resolve(root, "public/service-worker.js"), sw);

// --- 2) app-side build info --------------------------------------------------
mkdirSync(resolve(root, "src/generated"), { recursive: true });
writeFileSync(
  resolve(root, "src/generated/buildInfo.js"),
  [
    "// AUTO-GENERATED by scripts/gen-build-config.mjs — do not edit, do not commit.",
    `export const SW_VERSION = ${JSON.stringify(SW_VERSION)};`,
    `export const LAMBDA_URL = ${JSON.stringify(LAMBDA_URL)};`,
    `export const TENANT_NAME = ${JSON.stringify(TENANT_NAME)};`,
    `export const BUILD_TIME = ${JSON.stringify(BUILD_TIME)};`,
    "",
  ].join("\n")
);

console.log(
  `[gen-build-config] SW_VERSION=${SW_VERSION}  BASE_URL=${BASE_URL}  LAMBDA_URL=${LAMBDA_URL || "(unset — events queue only)"}  TENANT_NAME=${TENANT_NAME}`
);
